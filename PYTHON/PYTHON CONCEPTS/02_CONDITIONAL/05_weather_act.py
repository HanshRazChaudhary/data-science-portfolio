weather = input("Enter The Weather: ").capitalize()

if (weather == 'Sunny'):
    print("Weather Is Sunny, Go For A Walk")
elif (weather == 'Rainy'):
    print("Weather Is Rainny, Read A Book")
elif (weather == 'Snowy'):
    print("Weather Is Snowy, Build A Snowman")
else:
    print("Please Try Again Later!")